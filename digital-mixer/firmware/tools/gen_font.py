def main():
    out = ["// Generated by tools/gen_font.py - do not edit. Own 5x7 glyphs, ASCII 32..95.",
           "#pragma once", "#include <stdint.h>", "",
           "static const uint8_t FONT5X7[64][5] = {"]
    for code in range(32, 96):
        rows = G[chr(code)].split()
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), chr(code)
        cols = [sum(1 << y for y in range(7) if rows[y][x] == "#") for x in range(5)]
        esc = chr(code).replace("\\", "backslash")
        out.append("    {" + ", ".join(f"0x{c:02X}" for c in cols) + "},  // " + esc)
    out.append("};")
    Path(__file__).resolve().parent.parent.joinpath("src/core/font5x7.h").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
